// SPUDisasm gives one instruction as text.
func SPUDisasm(pc, w uint32) string {
	rT, rA, rB := w&0x7f, w>>7&0x7f, w>>14&0x7f
	switch w >> 28 {
	case 0x8, 0xb, 0xc, 0xd, 0xe, 0xf:
		n := map[uint32]string{8: "selb", 0xb: "shufb", 0xc: "mpya", 0xd: "fnms", 0xe: "fma", 0xf: "fms"}[w>>28]
		return fmt.Sprintf("%s r%d, r%d, r%d, r%d", n, w>>21&0x7f, rA, rB, rT)
	}
	switch w >> 25 {
	case 0x21:
		return fmt.Sprintf("ila r%d, 0x%x", rT, i18(w))
	case 0x08, 0x09:
		return "hbr*"
	}
	if n, ok := spuDis8[w>>24]; ok {
		return fmt.Sprintf("%s r%d, r%d, %d", n, rT, rA, i10(w))
	}
	if n, ok := spuDis9[w>>23]; ok {
		im := i16(w)
		switch w >> 23 {
		case 0x64, 0x66, 0x42, 0x40, 0x46, 0x44, 0x67, 0x47:
			return fmt.Sprintf("%s r%d, %05x", n, rT, (pc+uint32(im)*4)&lsMask)
		case 0x60, 0x62, 0x61, 0x41:
			return fmt.Sprintf("%s r%d, %05x", n, rT, uint32(im)*4&lsMask)
		}
		return fmt.Sprintf("%s r%d, 0x%x", n, rT, u16f(w))
	}
	if n, ok := spuDis10[w>>22]; ok {
		return fmt.Sprintf("%s r%d, r%d, %d", n, rT, rA, w>>14&0xff)
	}
	if n, ok := spuDis11[w>>21]; ok {
		switch w >> 21 {
		case 0x00d, 0x00f, 0x10d:
			return fmt.Sprintf("%s r%d, ch%d", n, rT, rA)
		case 0x000:
			return fmt.Sprintf("stop 0x%x", w&0x3fff)
		}
		return fmt.Sprintf("%s r%d, r%d, r%d (i7 %d)", n, rT, rA, rB, i7(w))
	}
	return fmt.Sprintf(".long 0x%08x", w)
}
