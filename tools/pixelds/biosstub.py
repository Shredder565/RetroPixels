#!/usr/bin/env python3
"""Assembles PixelDS's small BIOS stubs (exception vectors, the interrupt
dispatcher and the IntrWait loop) into cores/pixelds/nds/bios_stub.go.
Everything else the BIOS does is written in Go (nds/bios.go)."""
import sys
from keystone import *

COMMON = """
    b .
    movs pc, lr
    movs pc, lr
    subs pc, lr, #4
    subs pc, lr, #8
    b .
    b irq
    subs pc, lr, #4
irq:
    stmfd sp!, {r0-r3, r12, lr}
    %(handler_base)s
    add lr, pc, #0
    ldr pc, [r0, #-4]
    ldmfd sp!, {r0-r3, r12, lr}
    subs pc, lr, #4
intrwait:
    stmfd sp!, {r11, r12, lr}
    mrs r11, spsr
    stmfd sp!, {r11}
    and r11, r11, #0x80
    orr r11, r11, #0x1f
    msr cpsr_c, r11
    stmfd sp!, {r2, r3, lr}
    mov r12, #0x04000000
    %(flags_addr)s
    cmp r0, #0
    ldrne r2, [r3]
    bicne r2, r2, r1
    strne r2, [r3]
wait:
    mov r2, #1
    str r2, [r12, #0x208]
    %(halt)s
    ldr r2, [r3]
    ands r0, r1, r2
    beq wait
    bic r2, r2, r0
    str r2, [r3]
    ldmfd sp!, {r2, r3, lr}
    mov r11, #0xd3
    msr cpsr_c, r11
    ldmfd sp!, {r11}
    msr spsr_fsxc, r11
    ldmfd sp!, {r11, r12, lr}
    movs pc, lr
"""

ARM9 = COMMON % dict(
    handler_base="""mrc p15, 0, r0, c9, c1, 0
    mov r0, r0, lsr #12
    mov r0, r0, lsl #12
    add r0, r0, #0x4000""",
    flags_addr="""mrc p15, 0, r3, c9, c1, 0
    mov r3, r3, lsr #12
    mov r3, r3, lsl #12
    add r3, r3, #0x4000
    sub r3, r3, #8""",
    halt="mcr p15, 0, r0, c7, c0, 4")

ARM7 = COMMON % dict(
    handler_base="mov r0, #0x04000000",
    flags_addr="""mov r3, #0x03800000
    add r3, r3, #0xff00
    add r3, r3, #0xf8""",
    halt="""mov r2, #0x80
    strb r2, [r12, #0x301]""")

def asm(src):
    ks = Ks(KS_ARCH_ARM, KS_MODE_ARM)
    enc, _ = ks.asm(src, 0)
    words = [int.from_bytes(bytes(enc[i:i+4]), 'little') for i in range(0, len(enc), 4)]
    # where intrwait starts: count the lines before the label
    lines = [l.strip() for l in src.strip().splitlines() if l.strip()]
    n = 0
    for l in lines:
        if l.endswith(':'):
            if l == 'intrwait:': break
            continue
        n += 1
    return words, n * 4, lines

out = ["// Code generated by tools/pixelds/biosstub.py; DO NOT EDIT.", "",
       "package nds", ""]
for name, src in (("arm9", ARM9), ("arm7", ARM7)):
    words, iw, lines = asm(src)
    out.append("// %sBIOS: exception vectors, the interrupt dispatcher and IntrWait." % name)
    out.append("var %sBIOS = []uint32{" % name)
    code = [l for l in lines if not l.endswith(':')]
    for w, l in zip(words, code):
        out.append("\t0x%08x, // %s" % (w, l))
    out.append("}")
    out.append("")
    out.append("const %sIntrWait = 0x%x" % (name, iw))
    out.append("")
open(sys.argv[1], 'w').write("\n".join(out))
